#!/usr/bin/env python3
"""Builds the error page for any HTTP status code.

How the server tells the script which code to show (any one works):
    - query string:   /cgi-bin/error_page.py?code=404&path=/missing.html
    - environment:    STATUS_CODE=404  or  REDIRECT_STATUS=404
The requested path is optional: `path=` in the query string or REQUEST_URI.

Styles are inline so the page looks right even if /style.css is unreachable.
"""
import common as c

ERRORS = {
    400: ("Bad Request", "The server could not understand the request."),
    401: ("Unauthorized", "You need to be authenticated to see this page."),
    403: ("Forbidden", "You are not allowed to access this resource."),
    404: ("Not Found", "The page you asked for does not exist on this server."),
    405: ("Method Not Allowed", "This method is not allowed for this resource."),
    408: ("Request Timeout", "The request took too long to arrive."),
    411: ("Length Required", "This request needs a Content-Length header."),
    413: ("Payload Too Large", "The request body is larger than the server accepts."),
    414: ("URI Too Long", "The requested address is too long."),
    415: ("Unsupported Media Type", "The server does not accept this type of content."),
    500: ("Internal Server Error", "Something went wrong on the server."),
    501: ("Not Implemented", "The server does not support this feature."),
    502: ("Bad Gateway", "A CGI script failed or returned an invalid response."),
    503: ("Service Unavailable", "The server is too busy right now. Try again later."),
    504: ("Gateway Timeout", "A CGI script took too long to answer."),
    505: ("HTTP Version Not Supported", "The server does not support this HTTP version."),
}

fields = c.parse(c.query_string())
raw_code = fields.get("code") or c.env("STATUS_CODE", "REDIRECT_STATUS", default="500")
try:
    code = int(raw_code)
except ValueError:
    code = 500

if code in ERRORS:
    reason, message = ERRORS[code]
elif 400 <= code < 500:
    reason, message = "Client Error", "There is a problem with the request."
else:
    reason, message = "Server Error", "The server could not complete the request."

path = fields.get("path") or c.env("REQUEST_URI")
path_line = f'<p class="path">{c.esc(path)}</p>' if path else ""

# Client errors in blue, server errors in red.
accent = "#1e5eff" if code < 500 else "#c62f3d"

print(f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{code} {c.esc(reason)} · webserv</title>
    <link rel="icon" href="/favicon.ico">
    <style>
        body {{
            margin: 0;
            min-height: 100vh;
            display: flex;
            align-items: center;
            justify-content: center;
            font-family: system-ui, -apple-system, "Segoe UI", Roboto, Arial, sans-serif;
            background: #f4f7ff;
            color: #1a2240;
            text-align: center;
            padding: 20px;
            box-sizing: border-box;
        }}
        .box {{
            background: #ffffff;
            border: 1px solid #d9e2f7;
            border-top: 6px solid {accent};
            border-radius: 16px;
            padding: 48px 40px;
            max-width: 480px;
            width: 100%;
            box-shadow: 0 2px 12px rgba(24, 70, 196, 0.08);
        }}
        .code {{ font-size: 5.5rem; font-weight: 800; margin: 0; line-height: 1; color: {accent}; }}
        h1 {{ margin: 12px 0 8px; font-size: 1.4rem; color: #0b2a6f; }}
        p {{ color: #5b6585; margin: 0 0 24px; }}
        .path {{
            font-family: ui-monospace, Menlo, Consolas, monospace;
            font-size: 0.85rem;
            background: #e6eeff;
            color: #0b2a6f;
            padding: 6px 10px;
            border-radius: 6px;
            word-break: break-all;
        }}
        a {{
            display: inline-block;
            background: #1e5eff;
            color: #ffffff;
            padding: 10px 20px;
            border-radius: 8px;
            text-decoration: none;
            font-weight: 600;
        }}
        a:hover {{ background: #1846c4; }}
        small {{ display: block; margin-top: 28px; color: #8a93ad; }}
    </style>
</head>
<body>
    <div class="box">
        <p class="code">{code}</p>
        <h1>{c.esc(reason)}</h1>
        <p>{c.esc(message)}</p>
        {path_line}
        <a href="/">Back to home</a>
        <small>webserv &middot; error page generated by CGI</small>
    </div>
</body>
</html>""")
