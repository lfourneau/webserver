#!/usr/bin/env python3
"""Shared helpers for the webserv CGI scripts.

The scripts print HTML only (no CGI headers): the server sends the
script's output as the response body as-is.
"""
import html
import os
import sys
from urllib.parse import parse_qs


def env(*names, default=""):
    """Return the first environment variable that is set among `names`.

    The server currently uses HTTP_REQUEST_METHOD / HTTP_QUERY_STRING;
    the CGI standard uses REQUEST_METHOD / QUERY_STRING. Accept both.
    """
    for name in names:
        value = os.environ.get(name)
        if value:
            return value
    return default


def method():
    return env("REQUEST_METHOD", "HTTP_REQUEST_METHOD", default="GET").upper()


def query_string():
    return env("QUERY_STRING", "HTTP_QUERY_STRING")


def read_body():
    """Read the request body from stdin, up to EOF."""
    if method() != "POST":
        return ""
    try:
        data = sys.stdin.buffer.read()
    except Exception:
        return ""
    return data.decode("utf-8", errors="replace")


def parse(data):
    """Parse 'a=1&b=2' into {'a': '1', 'b': '2'} (first value wins)."""
    return {k: v[0] for k, v in parse_qs(data, keep_blank_values=True).items()}


def params():
    """GET parameters, merged with POST form data when there is a body.

    Returns (fields, raw_body).
    """
    fields = parse(query_string())
    body = read_body()
    if body:
        fields.update(parse(body.strip()))
    return fields, body


def esc(text):
    return html.escape(str(text))


def page(title, content):
    """Wrap `content` in the site layout (same CSS and nav as static pages)."""
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{esc(title)} · webserv</title>
    <link rel="icon" href="/favicon.ico">
    <link rel="stylesheet" href="/style.css">
    <script src="/app.js"></script>
</head>
<body>
    <header id="site-header"></header>
    <main>
{content}
    </main>
    <footer id="site-footer"></footer>
</body>
</html>"""


def generated_by(script):
    return (f'<p class="note">Generated by <code>{esc(script)}</code> '
            f'with Python {sys.version.split()[0]}, request method '
            f'<span class="badge {method().lower()}">{esc(method())}</span>.</p>')
