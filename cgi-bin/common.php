<?php
// Shared helpers for the webserv PHP CGI scripts.
//
// Works with both `php` and `php-cgi`: reads everything from getenv()
// and php://stdin instead of $_GET / $_POST.
// Prints HTML only (no headers). With `php-cgi`, run it with -q so it
// does not add its own headers to the output.

// First environment variable that is set (standard name, then the server's HTTP_ name).
function cgi_env(...$names)
{
    foreach ($names as $name) {
        $value = getenv($name);
        if ($value !== false && $value !== '')
            return $value;
    }
    return '';
}

function cgi_method()
{
    $m = cgi_env('REQUEST_METHOD', 'HTTP_REQUEST_METHOD');
    return $m === '' ? 'GET' : strtoupper($m);
}

function cgi_query_string()
{
    return cgi_env('QUERY_STRING', 'HTTP_QUERY_STRING');
}

function cgi_body()
{
    if (cgi_method() !== 'POST')
        return '';
    $body = file_get_contents('php://stdin');
    return $body === false ? '' : $body;
}

// GET parameters merged with the POST form body. Returns [fields, raw_body].
function cgi_params()
{
    parse_str(cgi_query_string(), $fields);
    $body = cgi_body();
    if ($body !== '') {
        parse_str(trim($body), $post);
        $fields = array_merge($fields, $post);
    }
    return [$fields, $body];
}

function esc($text)
{
    return htmlspecialchars((string)$text, ENT_QUOTES, 'UTF-8');
}

function page($title, $content)
{
    $t = esc($title);
    return <<<HTML
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>$t · webserv</title>
    <link rel="icon" href="/favicon.ico">
    <link rel="stylesheet" href="/style.css">
    <script src="/app.js"></script>
</head>
<body>
    <header id="site-header"></header>
    <main>
$content
    </main>
    <footer id="site-footer"></footer>
</body>
</html>

HTML;
}

function generated_by($script)
{
    $m = cgi_method();
    return '<p class="note">Generated by <code>' . esc($script) . '</code> with PHP ' . PHP_VERSION
        . ', request method <span class="badge ' . strtolower($m) . '">' . esc($m) . '</span>.</p>';
}
