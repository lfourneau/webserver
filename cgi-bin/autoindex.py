#!/usr/bin/env python3
"""Builds the autoindex page (directory listing).

The server runs this script internally when a directory is requested,
`autoindex on;` is set and there is no index file. It passes:
    - DIRECTORY:   real path of the directory on disk
    - REQUEST_URI: URI asked by the client (ends with '/')

Exit code != 0 (directory unreadable, ...) -> the server answers an error.
"""
import datetime
import os
import sys
from urllib.parse import quote

import common as c

directory = c.env("DIRECTORY")
uri = c.env("REQUEST_URI", default="/")
if not directory:
    sys.exit(1)

try:
    names = os.listdir(directory)
except OSError:
    sys.exit(1)

entries = []
for name in names:
    try:
        st = os.stat(os.path.join(directory, name))
    except OSError:
        continue
    is_dir = os.path.isdir(os.path.join(directory, name))
    entries.append((not is_dir, name.lower(), name, is_dir, st))
entries.sort()

rows = []
if uri != "/":
    rows.append('<tr><td><a href="../">../</a></td><td></td><td>-</td></tr>')
for _, _, name, is_dir, st in entries:
    shown = name + "/" if is_dir else name
    date = datetime.datetime.fromtimestamp(st.st_mtime).strftime("%Y-%m-%d %H:%M")
    size = "-" if is_dir else str(st.st_size)
    rows.append(f'<tr><td><a href="{quote(shown)}">{c.esc(shown)}</a></td>'
                f'<td>{date}</td><td>{size}</td></tr>')

print("Content-Type: text/html; charset=utf-8")
print()
print(f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Index of {c.esc(uri)} · webserv</title>
    <link rel="icon" href="/favicon.ico">
    <style>
        body {{
            margin: 0;
            padding: 32px 20px;
            font-family: system-ui, -apple-system, "Segoe UI", Roboto, Arial, sans-serif;
            background: #f4f7ff;
            color: #1a2240;
        }}
        .box {{
            max-width: 800px;
            margin: 0 auto;
            background: #ffffff;
            border: 1px solid #d9e2f7;
            border-top: 6px solid #1e5eff;
            border-radius: 16px;
            padding: 28px 32px;
        }}
        h1 {{ margin: 0 0 20px; font-size: 1.4rem; color: #0b2a6f; word-break: break-all; }}
        table {{ width: 100%; border-collapse: collapse; }}
        th, td {{ text-align: left; padding: 8px 10px; border-bottom: 1px solid #e6eeff; }}
        th {{ color: #5b6585; font-weight: 600; font-size: 0.85rem; }}
        td:nth-child(2), td:nth-child(3) {{ color: #5b6585; white-space: nowrap; }}
        td:nth-child(3), th:nth-child(3) {{ text-align: right; }}
        a {{ color: #1e5eff; text-decoration: none; word-break: break-all; }}
        a:hover {{ text-decoration: underline; }}
        small {{ display: block; margin-top: 20px; color: #8a93ad; }}
    </style>
</head>
<body>
    <div class="box">
        <h1>Index of {c.esc(uri)}</h1>
        <table>
            <tr><th>Name</th><th>Last modified</th><th>Size</th></tr>
            {chr(10).join(rows)}
        </table>
        <small>webserv &middot; autoindex generated by CGI</small>
    </div>
</body>
</html>""")
